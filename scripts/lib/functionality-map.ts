/**
 * Route-level functionality map (docs/system/functionality-map/): schema validation, value-map
 * cross-references, route-coverage checks, and deterministic Markdown view generation.
 *
 * The map is for AI agents. It records each route, its sections and the value-map facts and
 * figures each section reads; it has no per-control entries (owner decision, 22 November 2026).
 *
 * Pure core: callers pass parsed YAML documents and a RepoView so unit tests can run without
 * touching the real repository.
 */

export const FM_APPS = ["web", "marketing", "mobile"] as const;
type FmApp = (typeof FM_APPS)[number];

const FM_AUTH_MODES = ["required", "public", "anonymous-only", "admin"] as const;
type FmAuthMode = (typeof FM_AUTH_MODES)[number];

const FM_PAGE_KEYS = [
  "id",
  "app",
  "route",
  "title",
  "auth",
  "purpose",
  "route_file",
  "sections",
] as const;
const FM_SECTION_KEYS = ["id", "component", "facts_read", "figures_shown"] as const;

interface FmSection {
  id: string;
  component: string;
  facts_read?: string[];
  figures_shown?: string[];
}

export interface FmPage {
  id: string;
  app: FmApp;
  route: string;
  title: string;
  auth: FmAuthMode;
  purpose: string;
  route_file: string;
  sections: FmSection[];
  /** Top-level keys in the YAML that the schema does not allow (for example retired per-control keys). */
  unknown_keys?: string[];
}

interface FmExcludedRoute {
  route_file: string;
  reason: string;
}

export interface FmIndex {
  version: number;
  excluded_routes: FmExcludedRoute[];
  unmapped_allowlist?: string[];
}

export interface FmPageEntry {
  /** Repo-relative path to the YAML file, e.g. `docs/system/functionality-map/pages/web/retirement.yaml`. */
  filePath: string;
  /** Expected app derived from directory (`web` or `marketing`). */
  expectedApp: FmApp;
  /** Expected page ID derived from filename (`retirement`). */
  expectedId: string;
  page: FmPage;
}

export interface FmProblem {
  rule: FmRule;
  subject: string;
  message: string;
  severity: "error" | "warn";
}

export const FM_RULES = {
  malformed: "malformed",
  duplicateId: "duplicate-id",
  deadPath: "dead-path",
  unknownValueRef: "unknown-value-ref",
  unmappedRoute: "unmapped-route",
  deadAllowlist: "dead-allowlist",
  staleViews: "stale-views",
} as const;
type FmRule = (typeof FM_RULES)[number extends never ? never : keyof typeof FM_RULES];

export interface FmRepoView {
  exists(path: string): boolean;
  read(path: string): string | null;
}

export interface ValueMapRefs {
  factIds: ReadonlySet<string>;
  figureIds: ReadonlySet<string>;
}

const KEBAB_CASE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const VIEW_HEADER =
  "<!-- Generated by scripts/generate-functionality-map.ts from docs/system/functionality-map/. Do not edit by hand. -->\n\n";

const isNonEmptyString = (v: unknown): v is string => typeof v === "string" && v.trim().length > 0;

function isOneOf<T extends readonly string[]>(value: unknown, allowed: T): value is T[number] {
  return typeof value === "string" && (allowed as readonly string[]).includes(value);
}

/** Parses `docs/system/functionality-map/index.yaml`. */
export function parseFmIndex(text: string): FmIndex {
  const parsed = (Bun.YAML.parse(text) ?? {}) as Record<string, unknown>;
  return {
    version: typeof parsed.version === "number" ? parsed.version : 0,
    excluded_routes: Array.isArray(parsed.excluded_routes)
      ? (parsed.excluded_routes as FmExcludedRoute[])
      : [],
    ...(parsed.unmapped_allowlist !== undefined
      ? {
          unmapped_allowlist: Array.isArray(parsed.unmapped_allowlist)
            ? (parsed.unmapped_allowlist as string[])
            : [],
        }
      : {}),
  };
}

/** Parses a page YAML file (`pages/{web|marketing}/<page-id>.yaml`). */
export function parseFmPage(text: string): FmPage {
  const parsed = (Bun.YAML.parse(text) ?? {}) as Partial<FmPage> & Record<string, unknown>;
  const unknownKeys = Object.keys(parsed).filter(
    (k) => !(FM_PAGE_KEYS as readonly string[]).includes(k),
  );
  return {
    id: (parsed.id ?? "") as string,
    app: (parsed.app ?? "") as FmApp,
    route: (parsed.route ?? "") as string,
    title: (parsed.title ?? "") as string,
    auth: (parsed.auth ?? "") as FmAuthMode,
    purpose: (parsed.purpose ?? "") as string,
    route_file: (parsed.route_file ?? "") as string,
    sections: Array.isArray(parsed.sections) ? parsed.sections : [],
    ...(unknownKeys.length > 0 ? { unknown_keys: unknownKeys } : {}),
  };
}

/** Extracts fact and figure IDs from `docs/system/value-map.yaml` text. */
export function parseValueMapRefs(yamlText: string): ValueMapRefs {
  const parsed = (Bun.YAML.parse(yamlText) ?? {}) as {
    facts?: Array<{ id?: string }>;
    figures?: Array<{ id?: string }>;
  };
  const factIds = new Set<string>();
  const figureIds = new Set<string>();
  for (const f of parsed.facts ?? []) {
    if (isNonEmptyString(f?.id)) factIds.add(f.id);
  }
  for (const g of parsed.figures ?? []) {
    if (isNonEmptyString(g?.id)) figureIds.add(g.id);
  }
  return { factIds, figureIds };
}

/**
 * Discovers marketing page component files referenced by `apps/marketing/src/App.tsx`.
 * Resolves `./pages/<Name>` imports to `apps/marketing/src/pages/<Name>/<Name>.tsx` (or `index.ts`).
 */
export function discoverMarketingRoutes(repo: FmRepoView): string[] {
  const appPath = "apps/marketing/src/App.tsx";
  const text = repo.read(appPath);
  if (!text) return [];

  const importMap = new Map<string, string>();
  const importRe = /import\s+\{\s*([^}]+)\s*\}\s+from\s+["']\.\/pages\/([^"']+)["']/g;
  for (const match of text.matchAll(importRe)) {
    const names = match[1].split(",").map((s) => s.trim());
    const pageDir = match[2].trim();
    for (const name of names) {
      if (name) importMap.set(name, pageDir);
    }
  }

  const routeElementRe = /element=\{\s*<([A-Z][A-Za-z0-9]*)\b/g;
  const discovered = new Set<string>();
  for (const match of text.matchAll(routeElementRe)) {
    const componentName = match[1];
    const pageDir = importMap.get(componentName);
    if (!pageDir) continue;
    const candidates = [
      `apps/marketing/src/pages/${pageDir}/${pageDir}.tsx`,
      `apps/marketing/src/pages/${pageDir}/index.ts`,
      `apps/marketing/src/pages/${pageDir}.tsx`,
    ];
    const found = candidates.find((c) => repo.exists(c)) ?? candidates[0];
    discovered.add(found);
  }
  return [...discovered].sort();
}

/** Validates index.yaml, all page YAML entries, value-map refs, and route coverage. */
export function validateFunctionalityMap(opts: {
  index: FmIndex;
  pages: FmPageEntry[];
  repo: FmRepoView;
  valueMap: ValueMapRefs;
  discoveredRoutes: string[];
}): FmProblem[] {
  const { index, pages, repo, valueMap, discoveredRoutes } = opts;
  const problems: FmProblem[] = [];

  const add = (
    rule: FmRule,
    subject: string,
    message: string,
    severity: "error" | "warn" = "error",
  ) => {
    problems.push({ rule, subject, message, severity });
  };

  const checkPath = (owner: string, path: unknown) => {
    if (!isNonEmptyString(path)) {
      add(FM_RULES.malformed, owner, `${owner}: missing required file path`);
      return false;
    }
    if (path.includes("..")) {
      add(FM_RULES.malformed, owner, `${owner}: path must be repo-relative (no ".."): ${path}`);
      return false;
    }
    if (!repo.exists(path)) {
      add(FM_RULES.deadPath, `${owner} -> ${path}`, `${owner}: file does not exist: ${path}`);
      return false;
    }
    return true;
  };

  // --- index.yaml ---
  if (index.version !== 1) {
    add(
      FM_RULES.malformed,
      "index.version",
      `index.yaml: version must be 1 (got ${index.version})`,
    );
  }

  const excludedSet = new Set<string>();
  for (const [idx, entry] of index.excluded_routes.entries()) {
    const owner = `index.excluded_routes[${idx}]`;
    if (!entry || typeof entry !== "object") {
      add(FM_RULES.malformed, owner, `${owner}: must be an object with route_file and reason`);
      continue;
    }
    if (!isNonEmptyString(entry.reason)) {
      add(FM_RULES.malformed, owner, `${owner}: reason is required`);
    }
    if (checkPath(owner, entry.route_file)) {
      if (excludedSet.has(entry.route_file)) {
        add(
          FM_RULES.duplicateId,
          entry.route_file,
          `${owner}: duplicate excluded route_file "${entry.route_file}"`,
        );
      }
      excludedSet.add(entry.route_file);
    }
  }

  if (index.unmapped_allowlist !== undefined) {
    add(
      FM_RULES.deadAllowlist,
      "index.unmapped_allowlist",
      "index.yaml: unmapped_allowlist is retired in S4; remove it and map every route in pages/ or excluded_routes",
    );
  }

  // --- Pages ---
  const seenPagesByApp = new Set<string>();
  const mappedRouteFiles = new Set<string>();

  for (const entry of pages) {
    const { page, filePath, expectedApp, expectedId } = entry;
    const pOwner = `page ${filePath}`;

    if (page.unknown_keys && page.unknown_keys.length > 0) {
      add(
        FM_RULES.malformed,
        pOwner,
        `${pOwner}: unknown key(s) ${page.unknown_keys.join(", ")}; allowed: ${FM_PAGE_KEYS.join(", ")}`,
      );
    }

    if (!isNonEmptyString(page.id) || !KEBAB_CASE.test(page.id)) {
      add(
        FM_RULES.malformed,
        pOwner,
        `${pOwner}: id must be non-empty kebab-case (got "${page.id}")`,
      );
    } else if (page.id !== expectedId) {
      add(
        FM_RULES.malformed,
        pOwner,
        `${pOwner}: id "${page.id}" must match filename "${expectedId}.yaml"`,
      );
    }

    if (!isOneOf(page.app, FM_APPS)) {
      add(FM_RULES.malformed, pOwner, `${pOwner}: app must be one of ${FM_APPS.join(", ")}`);
    } else if (page.app !== expectedApp) {
      add(
        FM_RULES.malformed,
        pOwner,
        `${pOwner}: app "${page.app}" does not match folder "${expectedApp}"`,
      );
    }

    const pageKey = `${page.app}:${page.id}`;
    if (isNonEmptyString(page.id) && isOneOf(page.app, FM_APPS)) {
      if (seenPagesByApp.has(pageKey)) {
        add(
          FM_RULES.duplicateId,
          pageKey,
          `${pOwner}: duplicate page id "${page.id}" in app "${page.app}"`,
        );
      }
      seenPagesByApp.add(pageKey);
    }

    if (!isNonEmptyString(page.route)) {
      add(FM_RULES.malformed, pOwner, `${pOwner}: route is required`);
    }
    if (!isNonEmptyString(page.title)) {
      add(FM_RULES.malformed, pOwner, `${pOwner}: title is required`);
    }
    if (!isOneOf(page.auth, FM_AUTH_MODES)) {
      add(FM_RULES.malformed, pOwner, `${pOwner}: auth must be one of ${FM_AUTH_MODES.join(", ")}`);
    }
    if (!isNonEmptyString(page.purpose)) {
      add(FM_RULES.malformed, pOwner, `${pOwner}: purpose is required`);
    }
    if (checkPath(`${pOwner}.route_file`, page.route_file)) {
      mappedRouteFiles.add(page.route_file);
    }

    if (!Array.isArray(page.sections)) {
      add(FM_RULES.malformed, pOwner, `${pOwner}: sections must be an array`);
      continue;
    }

    const seenSections = new Set<string>();
    for (const [sIdx, section] of page.sections.entries()) {
      const sId = isNonEmptyString(section?.id) ? section.id : `[${sIdx}]`;
      const sOwner = `${page.app}/${page.id}.${sId}`;

      if (!section || typeof section !== "object") {
        add(FM_RULES.malformed, sOwner, `${sOwner}: section must be an object`);
        continue;
      }

      const unknownSectionKeys = Object.keys(section).filter(
        (k) => !(FM_SECTION_KEYS as readonly string[]).includes(k),
      );
      if (unknownSectionKeys.length > 0) {
        add(
          FM_RULES.malformed,
          sOwner,
          `${sOwner}: unknown key(s) ${unknownSectionKeys.join(", ")}; allowed: ${FM_SECTION_KEYS.join(", ")}`,
        );
      }

      if (!isNonEmptyString(section.id) || !KEBAB_CASE.test(section.id)) {
        add(
          FM_RULES.malformed,
          sOwner,
          `${sOwner}: section id must be non-empty kebab-case (got "${section.id}")`,
        );
      } else {
        if (seenSections.has(section.id)) {
          add(
            FM_RULES.duplicateId,
            sOwner,
            `${sOwner}: duplicate section id "${section.id}" in page "${page.id}"`,
          );
        }
        seenSections.add(section.id);
      }

      checkPath(`${sOwner}.component`, section.component);

      const refFields: Array<{
        key: "facts_read" | "figures_shown";
        kind: "fact" | "figure";
        validIds: ReadonlySet<string>;
      }> = [
        { key: "facts_read", kind: "fact", validIds: valueMap.factIds },
        { key: "figures_shown", kind: "figure", validIds: valueMap.figureIds },
      ];
      for (const { key, kind, validIds } of refFields) {
        const raw = section[key];
        if (raw === undefined) continue;
        if (!Array.isArray(raw)) {
          add(FM_RULES.malformed, `${sOwner}.${key}`, `${sOwner}: ${key} must be an array`);
          continue;
        }
        for (const refId of raw) {
          if (!isNonEmptyString(refId) || !validIds.has(refId)) {
            add(
              FM_RULES.unknownValueRef,
              `${sOwner}:${key}:${String(refId)}`,
              `${sOwner}: ${key} references unknown value-map ${kind} "${String(refId)}"`,
            );
          }
        }
      }
    }
  }

  // --- Route coverage ---
  for (const routeFile of discoveredRoutes) {
    const inMapped = mappedRouteFiles.has(routeFile);
    const inExcluded = excludedSet.has(routeFile);

    if (!inMapped && !inExcluded) {
      add(
        FM_RULES.unmappedRoute,
        routeFile,
        `unmapped route ${routeFile}: add a page YAML in docs/system/functionality-map/pages/ or list it in excluded_routes`,
        "error",
      );
    }
  }

  return problems;
}

const list = (items: string[] | undefined): string =>
  items && items.length > 0 ? items.map((i) => `\`${i}\``).join(", ") : "-";

function renderOverview(pages: FmPage[], index: FmIndex): string {
  const sorted = [...pages].sort((a, b) => `${a.app}/${a.id}`.localeCompare(`${b.app}/${b.id}`));
  const sectionCount = sorted.reduce((sum, p) => sum + p.sections.length, 0);

  let out = `${VIEW_HEADER}# Functionality map: overview\n\n`;
  out += `Mapped pages: ${sorted.length} | Sections: ${sectionCount} | Excluded routes: ${index.excluded_routes.length}\n`;

  for (const app of FM_APPS) {
    const appPages = sorted.filter((p) => p.app === app);
    out += `\n## ${app}\n`;
    if (appPages.length === 0) {
      out += "\n_No pages mapped yet._\n";
      continue;
    }
    for (const page of appPages) {
      out += `\n### ${page.id}: ${page.title}\n\n`;
      out += `- Route: \`${page.route}\` (auth: \`${page.auth}\`, file: \`${page.route_file}\`)\n`;
      out += `- Purpose: ${page.purpose}\n\n`;
      out += "| Section | Component | Facts read | Figures |\n";
      out += "|---|---|---|---|\n";
      for (const sec of page.sections) {
        out += `| \`${sec.id}\` | \`${sec.component}\` | ${list(sec.facts_read)} | ${list(sec.figures_shown)} |\n`;
      }
    }
  }
  return out;
}

function renderByFact(pages: FmPage[]): string {
  interface SectionRef {
    fullSectionId: string;
    app: string;
    page: string;
    route: string;
  }

  const factReaders = new Map<string, SectionRef[]>();
  const figureViewers = new Map<string, SectionRef[]>();

  const pushRef = (map: Map<string, SectionRef[]>, key: string, ref: SectionRef) => {
    const existing = map.get(key) ?? [];
    existing.push(ref);
    map.set(key, existing);
  };

  for (const page of pages) {
    for (const sec of page.sections) {
      const ref: SectionRef = {
        fullSectionId: `${page.app}.${page.id}.${sec.id}`,
        app: page.app,
        page: page.id,
        route: page.route,
      };
      for (const f of sec.facts_read ?? []) pushRef(factReaders, f, ref);
      for (const g of sec.figures_shown ?? []) pushRef(figureViewers, g, ref);
    }
  }

  const sortRefs = (refs: SectionRef[]) =>
    [...refs].sort((a, b) => a.fullSectionId.localeCompare(b.fullSectionId));

  let out = `${VIEW_HEADER}# Functionality map: by value-map fact and figure\n\n`;
  out += "## Facts\n\n";
  const allFactIds = [...factReaders.keys()].sort();
  if (allFactIds.length === 0) {
    out += "_No facts referenced yet._\n\n";
  } else {
    out += "| Fact ID | Section | Page | Route |\n|---|---|---|---|\n";
    for (const factId of allFactIds) {
      for (const r of sortRefs(factReaders.get(factId) ?? [])) {
        out += `| \`${factId}\` | \`${r.fullSectionId}\` | ${r.app}/${r.page} | \`${r.route}\` |\n`;
      }
    }
    out += "\n";
  }

  out += "## Figures\n\n";
  const allFigureIds = [...figureViewers.keys()].sort();
  if (allFigureIds.length === 0) {
    out += "_No figures referenced yet._\n";
  } else {
    out += "| Figure ID | Section | Page | Route |\n|---|---|---|---|\n";
    for (const figureId of allFigureIds) {
      for (const r of sortRefs(figureViewers.get(figureId) ?? [])) {
        out += `| \`${figureId}\` | \`${r.fullSectionId}\` | ${r.app}/${r.page} | \`${r.route}\` |\n`;
      }
    }
  }

  return out;
}

/** Renders the generated Markdown views before Biome formatting. */
export function renderFunctionalityViews(pages: FmPage[], index: FmIndex): Record<string, string> {
  return {
    "overview.md": renderOverview(pages, index),
    "by-fact.md": renderByFact(pages),
  };
}

/** Returns view filenames whose committed content differs from a freshly formatted render. */
export function staleFunctionalityViews(
  pages: FmPage[],
  index: FmIndex,
  committed: (name: string) => string | null,
  format: (name: string, text: string) => string,
): string[] {
  return Object.entries(renderFunctionalityViews(pages, index))
    .filter(([name, text]) => format(name, text) !== committed(name))
    .map(([name]) => name);
}
