import { randomBytes } from "node:crypto";
import { describe, expect, it } from "vitest";
import {
  bankingKeyFormatWarningMessage,
  bankingKeyFormatWarnings,
  looksLikeGeneratedKey,
  resolveBankingKeyring,
} from "./crypto";

// E3 D-11: keys that are not 32 generated random bytes are warned about, never refused.
// Sample keys are built at runtime; none is a real secret.
const hexKey = () => randomBytes(32).toString("hex");
const base64Key = () => randomBytes(32).toString("base64");
const base64UrlKey = () => randomBytes(32).toString("base64url");
/** Accepted today (32 characters) but a passphrase, not generated bytes. */
const passphrase = () => ["plain", "words", "make", "a", "passphrase"].join("-").padEnd(32, "x");

const strict = (vars: Record<string, string>) => ({ NODE_ENV: "production", ...vars });

describe("looksLikeGeneratedKey", () => {
  it("accepts 64 hex characters and base64 or base64url of 32 bytes", () => {
    expect(looksLikeGeneratedKey(hexKey())).toBe(true);
    expect(looksLikeGeneratedKey(hexKey().toUpperCase())).toBe(true);
    expect(looksLikeGeneratedKey(base64Key())).toBe(true);
    expect(looksLikeGeneratedKey(base64UrlKey())).toBe(true);
  });

  it("does not accept a passphrase, 16 bytes of hex or 33 bytes of hex", () => {
    expect(looksLikeGeneratedKey(passphrase())).toBe(false);
    expect(looksLikeGeneratedKey(randomBytes(16).toString("hex"))).toBe(false);
    expect(looksLikeGeneratedKey(randomBytes(33).toString("hex"))).toBe(false);
  });
});

describe("bankingKeyFormatWarnings", () => {
  it("warns about a 32-character passphrase as version 1 of the single key", () => {
    expect(
      bankingKeyFormatWarnings(strict({ BANKING_TOKEN_ENCRYPTION_KEY: passphrase() })),
    ).toEqual([{ variable: "BANKING_TOKEN_ENCRYPTION_KEY", version: 1 }]);
  });

  it("is silent for a hex or base64 generated key", () => {
    for (const key of [hexKey(), base64Key()]) {
      expect(bankingKeyFormatWarnings(strict({ BANKING_TOKEN_ENCRYPTION_KEY: key }))).toEqual([]);
    }
  });

  it("names each listed version that is not generated, and only those", () => {
    const env = strict({
      BANKING_TOKEN_ENCRYPTION_KEY: passphrase(),
      BANKING_TOKEN_ENCRYPTION_KEYS: `3:${hexKey()},2:${passphrase()},1:${base64Key()}`,
    });
    // The list takes over from the single key, so the single passphrase is not reported.
    expect(bankingKeyFormatWarnings(env)).toEqual([
      { variable: "BANKING_TOKEN_ENCRYPTION_KEYS", version: 2 },
    ]);
  });

  it("leaves a malformed list to the resolver, which still refuses it", () => {
    const env = strict({ BANKING_TOKEN_ENCRYPTION_KEYS: "not-a-list" });
    expect(bankingKeyFormatWarnings(env)).toEqual([]);
    expect(() => resolveBankingKeyring(env)).toThrow(/BANKING_TOKEN_ENCRYPTION_KEYS/);
  });

  it("does not warn about the development default when nothing is configured", () => {
    expect(bankingKeyFormatWarnings({ NODE_ENV: "test" })).toEqual([]);
  });

  it("still refuses a short key exactly as before; the warning does not loosen anything", () => {
    expect(() =>
      resolveBankingKeyring(strict({ BANKING_TOKEN_ENCRYPTION_KEY: "k".repeat(31) })),
    ).toThrow("BANKING_TOKEN_ENCRYPTION_KEY must be set to at least 32 characters.");
  });
});

describe("bankingKeyFormatWarningMessage", () => {
  it("names the variable, version, expected form and runbook, and never the secret or its length", () => {
    const secret = passphrase();
    const [warning] = bankingKeyFormatWarnings(strict({ BANKING_TOKEN_ENCRYPTION_KEY: secret }));
    const message = bankingKeyFormatWarningMessage(warning!);
    expect(message).toContain("BANKING_TOKEN_ENCRYPTION_KEY key version 1");
    expect(message).toContain("openssl rand -hex 32");
    expect(message).toContain("docs/runbooks/bank-token-key-rotation.md");
    expect(message).not.toContain(secret);
    // A longer passphrase gives the identical line, so nothing about the secret (its length
    // included) is in it.
    const [longer] = bankingKeyFormatWarnings(
      strict({ BANKING_TOKEN_ENCRYPTION_KEY: secret.padEnd(47, "y") }),
    );
    expect(bankingKeyFormatWarningMessage(longer!)).toBe(message);
  });
});
