#!/usr/bin/env bash
# PreToolUse (Edit|Write|MultiEdit): block hand edits to generated or tool-owned files.
file=$(jq -r '.tool_input.file_path // empty')
[ -z "$file" ] && exit 0
case "$file" in
  */bun.lock|*/.env|*/.env.*|*/CHANGELOG.md|*/.release-please-manifest.json|*/styled-system/*)
    case "$file" in
      */.env.example|*/.env.*.example) exit 0 ;;
    esac
    {
      echo "Blocked: $file is generated or owned by tooling and must not be edited by hand."
      echo "- bun.lock: change dependencies with bun add/remove/install"
      echo "- CHANGELOG.md, .release-please-manifest.json: owned by release-please"
      echo "- styled-system/: regenerated by Panda CSS codegen"
      echo "- .env*: secrets; ask the user to edit them"
    } >&2
    exit 2 ;;
esac
exit 0
